// Token Radar, model radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks the pre-token protocols that can be standalone launches. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol), and
// the board sets aside the ones that cannot be a launch of their own, by the same rule the
// snapshot's watchlist uses: exchanges, versioned pools of another protocol, Bridge and
// Canonical Bridge, Liquid Staking, Liquid Restaking and Restaked BTC, names carrying a whole
// word wrapped, staked or staking, and names beginning with an exchange's name. A wrapped or
// staked product of a token that already trades is not a token that does not exist yet — WBTC
// is Bitcoin on Ethereum, Binance staked ETH is ETH in Binance's staking product — so they are
// shown in the dashboard's Set-aside view with the reason, never ranked as launches. The
// watchlist is the floor: every one of its 40 slugs is on the board, and the radar adds every
// other rankable pre-token protocol below the floor, so the board is the whole pre-token
// universe the snapshot can see, not a top-200 cut.
//
// Implied value follows only from the snapshot's own figures. No protocol name is special-cased;
// the same function scores every row:
//
//   size     = tvl_usd ^ 0.92                       (sublinear: value grows with size, but a
//                                                    protocol twice as big is not twice as
//                                                    valuable as a launch)
//   base     = size x 0.30
//   growth   = clamp(change_7d, -50, 150) per cent
//   growthM  = 1 + (growth / 100) x 0.60
//   age      = days from listed_at to as_of (unknown: 365)
//   maturity = 0.55 + 0.45 x min(age, 1460) / 1460  (a long run with no token is a patience
//                                                    premium: the launch, if it comes, has had
//                                                    longer to accumulate users)
//   breadth  = 1 + 0.04 x min(chains - 1, 5)        (multi-chain reach)
//   category = 1.00, or 0.90 when DefiLlama names no category.
//   implied  = max(1, round(base x growthM x maturity x breadth x category))
//
// Protocols whose token already trades are never ranked by implied value. They are set aside and
// shown in the dashboard's Live view at the market's own value (market cap), so the board never
// mixes a model's claim with a market price.

/** One protocol entry: exactly the ten fields the sealed snapshot carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

